#!/usr/bin/env python3
"""Generates build/web/pistak_sw.js: precaches every file of the web build so
PISTAK opens with no connection after the first visit.

Usage: python3 tool/gen_service_worker.py build/web
"""
import hashlib, json, os, sys

root = sys.argv[1] if len(sys.argv) > 1 else 'build/web'
skip = {'pistak_sw.js', 'flutter_service_worker.js', '_headers'}
files, h = [], hashlib.sha256()
for dirpath, _, names in os.walk(root):
    for n in sorted(names):
        full = os.path.join(dirpath, n)
        rel = os.path.relpath(full, root).replace(os.sep, '/')
        if rel in skip or rel.endswith('.map'):
            continue
        files.append(rel)
        with open(full, 'rb') as f:
            h.update(rel.encode()); h.update(f.read())
files.sort()
version = h.hexdigest()[:16]
precache = ['./'] + [f for f in files if f != 'index.html'] + ['index.html']

sw = f"""// GENERATED by tool/gen_service_worker.py — do not edit.
const VERSION = 'pistak-{version}';
const PRECACHE = {json.dumps(precache)};

self.addEventListener('install', (event) => {{
  event.waitUntil(
    caches.open(VERSION).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting())
  );
}});

self.addEventListener('activate', (event) => {{
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== VERSION).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
}});

// Cache-first for the app shell; runtime-cache anything else fetched with GET
// (e.g. fonts) so the next offline start still works. Never caches API calls.
self.addEventListener('fetch', (event) => {{
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.pathname.startsWith('/api/')) return;
  event.respondWith(
    caches.match(req, {{ ignoreSearch: url.origin === self.location.origin }}).then((hit) => {{
      if (hit) return hit;
      return fetch(req).then((res) => {{
        if (res && (res.ok || res.type === 'opaque')) {{
          const copy = res.clone();
          caches.open(VERSION).then((c) => c.put(req, copy));
        }}
        return res;
      }}).catch(() => req.mode === 'navigate' ? caches.match('index.html') : Response.error());
    }})
  );
}});
"""
with open(os.path.join(root, 'pistak_sw.js'), 'w') as f:
    f.write(sw)
print(f'pistak_sw.js: {len(precache)} files, version {version}')
